const languageIndex = { ru: 0, en: 1, de: 2 };

const humanizeIdentifier = (identifier) => String(identifier || '')
  .replace(/^(quest|profile|clan|clans|nav|map|shop|statistics)_/, '')
  .replace(/_/g, ' ')
  .replace(/^./, (letter) => letter.toUpperCase());

export const translate = (identifier, language, fallback = null, params = {}) => {
  const normalizedLanguage = normalizeLanguage(language);
  const entry = messages[identifier];
  let text = entry?.[languageIndex[normalizedLanguage]];

  if (!text && fallback) text = fallback;
  if (!text) text = humanizeIdentifier(identifier);

  return String(text).replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  ));
};

export const hasTranslation = (identifier, language) => Boolean(
  messages[identifier]?.[languageIndex[normalizeLanguage(language)]],
);

